// Get all jobs
export const getAllJobs = () => allJobs;

// Get jobs by category
export const getJobsByCategory = (category) => {
  if (!category || category === "all") return allJobs;
  return allJobs.filter((job) => job.category === category);
};

// Get a single job by ID
export const getJobById = (id) => {
  return allJobs.find((job) => job.id === parseInt(id));
};

// Get job count by category
export const getJobCountByCategory = (category) => {
  if (!category || category === "all") return allJobs.length;
  return allJobs.filter((job) => job.category === category).length;
};

